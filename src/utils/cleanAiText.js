// =============================================================================
// utils/cleanAiText.js — تنظيف نصوص ردود الذكاء الاصطناعي للعرض النهائي
// -----------------------------------------------------------------------------
// يزيل علامات Markdown التحريرية التي تظهر حرفياً في الشات (الذي لا يعرض
// Markdown): التأكيد «**»، المائل «*»، التسطير «_»، رؤوس العناوين «#»، وعلامات
// الاقتباس «>». يحوّل سطور النقاط («-» و«*» والأرقام «1.») إلى نقاط «•» موحدة
// ليظهر الرد نظيفاً بلا «*» وبنسق مرتب. لا يغيّر الأرقام أو المبالغ أو أسماء
// البنود، ويمرّر أي نص غير نصي كما هو.
// =============================================================================

/**
 * تنظيف نص رد AI من علامات التنسيق الخام وإرجاع نص نظيف جاهز للعرض.
 * غير نقي 100% — لا يعتمد على DOM، ويمرر القيم غير النصية دون تغيير.
 */
export function cleanAiText(text) {
  if (typeof text !== 'string' || !text) return text
  return String(text)
    // تأكيد عريض **نص** → نص
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    // مائل *نص* → نص (لا يلتقط سطر النقطة المنفرد بدون نجمة إغلاق)
    .replace(/\*([^*\n]+)\*/g, '$1')
    // تسطير مزدوج/مفرد
    .replace(/__(.+?)__/g, '$1')
    .replace(/_([^_\n]+)_/g, '$1')
    // تحويل سطور النقاط (- أو *) إلى نقاط موحدة «•»
    .replace(/^[ \t]*[-*]\s+/gm, '• ')
    // تحويل القوائم المرقمة «1.» / «1)» إلى نقاط
    .replace(/^[ \t]*\d+[.)]\s+/gm, '• ')
    // رؤوس العناوين #/##/### → إبقاء النص فقط
    .replace(/^#{1,6}\s*/gm, '')
    // علامات الاقتباس
    .replace(/^[ \t]*>\s?/gm, '')
    // أي نجمات متبقية
    .replace(/\*/g, '')
    // مسافات زائدة نهاية الأسطر + تكرار الأسطر الفارغة
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}
